const fs=require('fs');
const path=require('path');
const assert=require('assert');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const runtime=read('src/core/automation-test-runtime.js');
const main=read('main.js');
const match=runtime.match(/const VERSION='(\d+)\.(\d+)\.(\d+)'/);
assert(match,'Automation Test runner version must be declared.');
const version=match.slice(1).map(Number);
assert(version[0]>1||(version[0]===1&&(version[1]>1||(version[1]===1&&version[2]>=0))),'Automation Test runner must be v1.1.0 or newer.');
const discovery=runtime.slice(runtime.indexOf('function enabledTopActivities'),runtime.indexOf('async function rendererPlotSmoke'));
assert(discovery.includes("workspaceRole==='top'")&&discovery.includes('topContractReady'),'TOP discovery must use the workspace contract.');
assert(!discovery.includes('&&row?.hasWindow'),'TOP discovery must not require an already-open independent window.');
assert(runtime.includes("'top.coverage'")&&runtime.includes('testedTopCount===tops.length'),'Automation Test must assert explicit TOP renderer coverage.');
assert(runtime.includes('passedTopCount===tops.length'),'TOP coverage must require every exercised renderer to reach ready.');
assert(runtime.includes("'plot.interactions'")&&runtime.includes('ScientificPlot shared interaction controllers'),'Built-app automation must exercise the shared ScientificPlot controller surface.');
assert(runtime.includes("'runtime.package-mode'")&&runtime.includes('isPackaged===false'),'Automation Test must distinguish development runtime from packaged build validation.');
assert(runtime.includes('coverage:{topRenderers:{discovered:tops.length,tested:testedTopCount,passed:passedTopCount'),'Report must persist discovered/tested/passed TOP coverage metadata.');
assert(runtime.includes('scientificPlotControllers'),'Report must disclose which shared plot controllers were verified.');
assert(main.includes('runDiagnosticActivitySmoke')&&main.includes('waitForAuxiliaryDiagnosticOutcome'),'TOP checks must still create and await a real Electron renderer.');
console.log('v3.46 Automation Test Center TOP coverage regression checks passed.');
