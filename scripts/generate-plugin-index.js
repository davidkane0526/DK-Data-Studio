const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const pluginsDir = path.join(root, 'src', 'plugins');
const outPath = path.join(pluginsDir, 'plugin-index.generated.js');

const entries = [];
for (const name of fs.readdirSync(pluginsDir).sort()) {
  if (name.startsWith('_')) continue;
  const dir = path.join(pluginsDir, name);
  if (!fs.statSync(dir).isDirectory()) continue;
  const manifestPath = path.join(dir, 'plugin.json');
  if (!fs.existsSync(manifestPath)) continue;
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if (manifest.enabled === false) continue;
  const entry = String(manifest.entry || 'plugin.js').replace(/\\/g, '/');
  entries.push(`plugins/${name}/${entry}`);
}

const source = `// AUTO-GENERATED by scripts/generate-plugin-index.js. Do not edit.\n`
  + `window.DKDS_BUILTIN_PLUGIN_ENTRIES = ${JSON.stringify(entries, null, 2)};\n`;
fs.writeFileSync(outPath, source, 'utf8');
console.log(`Generated ${path.relative(root, outPath)} with ${entries.length} plugin entries.`);
