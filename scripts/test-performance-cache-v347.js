const assert=require('assert');
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const {performance}=require('perf_hooks');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const context={console,performance,structuredClone,setTimeout,clearTimeout,Map,Set,WeakMap,Date,Math,JSON,Number,String,Array,Object,Int8Array};
context.window=context;context.globalThis=context;vm.createContext(context);
for(const file of ['src/science/common.js','src/core/performance-runtime.js','src/science/peaks.js','src/core/data-model.js'])vm.runInContext(read(file),context,{filename:file});
const perf=context.DKDSPerformance;
assert(perf&&Number(String(perf.VERSION||'0').split('.')[0])>=1,'Performance Runtime v1+ must load.');
perf.clear('test.memo');perf.resetMetrics('test.memo');let computeCount=0;
assert.strictEqual(perf.memo('test.memo','x',()=>{computeCount+=1;return 7;}),7);
assert.strictEqual(perf.memo('test.memo','x',()=>{computeCount+=1;return 9;}),7);
assert.strictEqual(computeCount,1,'bounded value cache must reuse identical input');
const sweep={id:'s1',step:.01,points:Array.from({length:401},(_,i)=>{const v=-2+i*.01;return {v,i:1e-9*(1+.15*v)+4e-9*Math.exp(-(((v-.45)/.08)**2))};})};
const a=context.DKDSScience.transformSweep(sweep,'didv',{radius:2});
const b=context.DKDSScience.transformSweep(sweep,'didv',{radius:2});
assert.strictEqual(a,b,'transformSweep must reuse the immutable sweep transform result');
const transformStats=perf.snapshot().namespaces.find(row=>row.namespace==='science.transformSweep');
assert(transformStats?.hits>=1&&transformStats?.misses>=1,'transformSweep cache must expose hit/miss metrics');
const D=context.DKDSData;const store=D.createStore();
assert.strictEqual(store.revision(),0);assert.strictEqual(store.revision('data.table'),0);
const table=D.createTable({id:'table:1',name:'T',columns:[{key:'Vd',name:'Vd',role:'x',unit:'V',values:[0,1]},{key:'Id',name:'Id',role:'y',unit:'A',values:[1e-9,2e-9]}]});
store.add(table);assert.strictEqual(store.revision(),1);assert.strictEqual(store.revision('data.table'),1);
const derived=D.createAnalysisResult({id:'result:1',name:'R',summary:{ok:true}});store.add(derived);
assert.strictEqual(store.revision('data.table'),1,'derived artifacts must not invalidate source-table revision caches');
console.log('v3.47 Performance Runtime, transform cache and artifact kind-revision checks passed.');
