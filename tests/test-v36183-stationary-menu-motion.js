'use strict';
const fs=require('fs');
const assert=require('assert');
const path=require('path');
const root=path.resolve(__dirname,'..');
const readComposition=require('./helpers/read-composition');
const read=file=>fs.readFileSync(file,'utf8');
const presentation=read('src/styles/presentation/dialogs.css');
const motion=read('src/styles/theme/contract.css');
const kernel=readComposition(root,'src/core/plugins/kernel');
assert(!presentation.includes('@keyframes dkui-menu-in')&&!motion.includes('@keyframes dkui-menu-in'),'geometric command-menu entrance keyframe must stay removed');
assert(motion.includes('animation:none;transform:none'),'Core menus must not animate or move into place under the central Theme motion contract');
assert(/:where\(button,.plugin-menu-item,\[role=\"menuitem\"\],.menu-item\):is\(:hover,:active,:focus-visible\)\{\s*transform:none/.test(motion),'menu items must not lift on hover/press under the central Theme motion contract');
const visibility=kernel.indexOf("menu.style.visibility='hidden';");
const reveal=kernel.indexOf("menu.classList.remove('hidden');",visibility);
const position=kernel.indexOf('positionCommandMenuPortal(button,menu);',reveal);
const show=kernel.indexOf("menu.style.visibility='';",position);
assert(visibility>=0&&reveal>visibility&&position>reveal&&show>position,'portal must resolve geometry while paint-hidden before reveal');
console.log('v3.61.83 stationary menu motion contract OK');
