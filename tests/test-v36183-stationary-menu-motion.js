'use strict';
const fs=require('fs');
const assert=require('assert');
const path=require('path');
const root=path.resolve(__dirname,'..');
const readComposition=require('./helpers/read-composition');
const read=file=>fs.readFileSync(file,'utf8');
const presentation=read('src/styles/presentation/dialogs.css');
const motion=read('src/styles/motion/recipes.css');
const kernel=readComposition(root,'src/core/plugins/kernel');
assert(!presentation.includes('@keyframes dkui-menu-in')&&!motion.includes('@keyframes dkui-menu-in'),'geometric command-menu entrance keyframe must stay removed');
assert(/body\.dkds-modern-ui\s+:where\(\.command-menu,[^)]*\)\s*\{[^}]*animation:none;[^}]*transform:none/s.test(motion),'Core menus must not animate or move into place under the central Motion Recipes contract');
assert(/:where\(button,.plugin-menu-item,\[role="menuitem"\],.menu-item\)\{\s*transform:none/.test(motion),'menu items must remain stationary under the central Motion Recipes contract');
const visibility=kernel.indexOf("menuSet(menu,'visibility','hidden');");
const reveal=kernel.indexOf("menu.classList.remove('hidden');",visibility);
const position=kernel.indexOf('positionCommandMenuPortal(button,menu);',reveal);
const theme=kernel.indexOf('prepareCommandMenuForPaint(menu);',reveal);
const show=kernel.indexOf("menuRemove(menu,'visibility');",position);
assert(visibility>=0&&reveal>visibility&&theme>reveal&&position>theme&&show>position,'portal must synchronously compose appearance and resolve geometry while paint-hidden before reveal');
console.log('v3.61.83 stationary menu motion contract OK');
