'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const json=rel=>JSON.parse(read(rel));
const app=json('package.json');
const expo=json('mobile/app.json').expo;
const structure=read('src/styles/structure/sdk-semantic-surfaces.css');
const paint=read('src/styles/presentation/plugin-chrome.css');
const shell=read('src/styles/presentation/shell.css');
const mobile=read('src/styles/platform/native-workspace-presentation.css');

assert(/^3\.68\./.test(app.version),'Portable handle regression contract must remain on the 3.68 line.');
assert.strictEqual(expo.version,app.version);
assert(expo.android.versionCode>=85);
assert(structure.includes('right:0;bottom:0;z-index:12;width:36px;height:36px'),'The invisible resize hit target must remain 36×36.');
assert(structure.includes('clip-path:polygon(100% 0,100% 100%,0 100%)'),'Keep the accepted 3.68.52 corner-anchored clipped geometry.');
assert(structure.includes('width:18px;height:18px')&&structure.includes('width:15px;height:15px'),'The exact accepted 18/15 geometry must remain intact.');
assert(paint.includes('color-mix(in srgb,var(--dkui-component-floating-chrome-indicator')&&paint.includes('color-mix(in srgb,var(--dkui-component-floating-chrome-border-active'),'Both clipped regions must stay in the active theme floatingChrome family.');
assert(!paint.includes('backdrop-filter')&&!shell.includes('--dkui-portable-corner-blur'),'The rejected surface-glass/blur treatment must stay removed.');
assert(!shell.includes('--dkui-portable-corner-glass')&&!/portable-corner-inner:[^;]*surface/i.test(shell),'The inner triangle must never return to a panel-surface glass role.');
const handlePaint=(paint.match(/\.dkds-portable-resize-handle\{[\s\S]*?\.plugin-card-icon/)||[''])[0];
assert(!handlePaint.includes('border-top:1px')&&!handlePaint.includes('border-left:1px')&&!handlePaint.includes('rotate(-45deg)'),'No artificial crease, slash or page-flap border may be added.');
assert(!shell.includes('--dkui-portable-corner-')&&paint.includes('--dkui-component-floating-chrome-indicator'),'Portable handle material must come from Theme component appearance rather than shell-owned RGB/mix literals.');
assert(!shell.includes('--dkui-portable-corner-fill'),'The later full-triangle fill model must remain retired.');
assert(!mobile.includes('>.dkds-portable-resize-handle::before')&&!mobile.includes('>.dkds-portable-resize-handle::after'),'Desktop and Mobile must keep one Core paint owner.');
console.log('PortableView 3.68.52 geometry + flat same-family material contract PASS.');
