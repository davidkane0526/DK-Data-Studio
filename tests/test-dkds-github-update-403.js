'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const native=require('../desktop/native-update');
const ui=read('desktop/ui-hot-update.js');
assert.equal(native.githubHttpError(403,{'x-ratelimit-remaining':'0','x-ratelimit-reset':'1800000000'},native.RELEASES).httpStatus,403);
assert.match(native.githubHttpError(403,{'x-ratelimit-remaining':'0'},native.RELEASES).message,/限流/);
assert.match(native.githubHttpError(403,{'x-ratelimit-remaining':'50'},native.RELEASES).message,/拒绝访问/);
assert.match(native.githubHttpError(429,{'retry-after':'10'},native.RELEASES).message,/限流/);
assert.match(native.RELEASES,/per_page=100/);
assert(ui.includes("const {openHttps,readJson,RELEASES}=require('./native-update')"));
assert(ui.includes('const API=RELEASES;'));
assert(read('desktop/native-update.js').includes('if(cached?.pending)return cached.pending'));
assert(read('desktop/native-update.js').includes('RELEASE_STALE_MS'));
const android=read('mobile/plugins/DkdsAppUpdate.template');
assert(android.includes('static JSONArray fetchReleases() throws Exception'));
assert(android.includes('synchronized(RELEASE_LOCK)'));
assert(android.includes('X-RateLimit-Remaining'));
assert(android.includes('Retry-After'));
assert(android.includes('GithubHttpException'));
assert(android.includes('JSONArray releases=fetchReleases();'));
assert(read('mobile/plugins/DkdsUiHotUpdate.template').includes('JSONArray releases=DkdsAppUpdateManager.fetchReleases();'));
