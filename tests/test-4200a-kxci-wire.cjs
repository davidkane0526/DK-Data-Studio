'use strict';
const assert=require('node:assert/strict');
const wire=require('../src/4200a-fspro/domain/kxci-wire');
assert.deepEqual([...wire.encode('*IDN?')],[42,73,68,78,63,0]);
assert.deepEqual([...wire.encode("DO 'I1'")].slice(-1),[0]);
for(const payload of ['*RST\n','ME1\r','A\0B','', '\u0100','X'.repeat(4097)])assert.throws(()=>wire.encode(payload),/Invalid KXCI/);
const d=wire.createDecoder();
assert.deepEqual(d.push(Uint8Array.from([0x31,0x32])),[]);
assert.equal(d.pendingBytes(),2);
let rows=d.push(Uint8Array.from([0x33,0,0x34,0x35,0,0x36]));
assert.deepEqual(rows.map(x=>x.text),['123','45']);
assert.deepEqual([...rows[0].bytes],[49,50,51]);
rows=d.push(Uint8Array.from([0x37,0]));
assert.deepEqual(rows.map(x=>x.text),['67']);
assert.equal(d.pendingBytes(),0);
assert.throws(()=>wire.createDecoder({maxBytes:0}),/limit/);
assert.throws(()=>wire.createDecoder({maxBytes:wire.MAX_REPLY_BYTES+1}),/limit/);
const narrow=wire.createDecoder({maxBytes:3});
narrow.push(Uint8Array.from([49,50,51]));
assert.throws(()=>narrow.push(Uint8Array.from([52])),/exceeds/);
console.log('4200A KXCI frame codec: ASCII command gating, NULL terminator, fragmented responses, byte cap');
