'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const json=rel=>JSON.parse(read(rel));
const walk=rel=>{
  const dir=path.join(root,rel),out=[];
  for(const entry of fs.readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name))){
    const child=path.join(rel,entry.name).replaceAll('\\','/');
    if(entry.isDirectory())out.push(...walk(child));else out.push(child);
  }
  return out;
};
function tuple(v){return String(v||'0.0.0').split(/[.-]/).slice(0,3).map(x=>Number(x)||0);}
function atLeast(a,b){for(let i=0;i<3;i++){if((a[i]||0)!==(b[i]||0))return(a[i]||0)>(b[i]||0);}return true;}
function storedZipEntries(buffer){
  const entries=new Map();let offset=0;
  while(offset+30<=buffer.length&&buffer.readUInt32LE(offset)===0x04034b50){
    const method=buffer.readUInt16LE(offset+8),size=buffer.readUInt32LE(offset+18),nameLen=buffer.readUInt16LE(offset+26),extraLen=buffer.readUInt16LE(offset+28);
    assert.strictEqual(method,0,'SDK export archive must stay dependency-free/deterministic with stored ZIP entries.');
    const name=buffer.subarray(offset+30,offset+30+nameLen).toString('utf8');
    const start=offset+30+nameLen+extraLen,end=start+size;
    entries.set(name,buffer.subarray(start,end));offset=end;
  }
  return entries;
}

const pkg=json('package.json');
assert(atLeast(tuple(pkg.version),[3,70,0]),'SDK export is new post-archive capability and must live on the 3.70.x line.');
const html=read('src/index.html');
const exportPos=html.indexOf('id="pluginManagerExportSdkBtn"'),diagPos=html.indexOf('id="pluginManagerDiagnosticsBtn"');
assert(exportPos>=0&&diagPos>exportPos,'Plugin Manager must place 导出SDK immediately to the left of 复制诊断.');
assert(/id="pluginManagerExportSdkBtn"[^>]*data-dkds-native-save="export"[^>]*>导出SDK<\/button>/.test(html),'SDK export must opt into the explicit native export-intent gate.');

const manager=read('src/core/plugins/manager-ui.js');
assert(manager.includes("$('#pluginManagerExportSdkBtn').onclick=exportSdk")&&manager.includes('window.electronAPI?.exportSdkBundle'),'Plugin Manager must bind the SDK export action to the shared platform bridge.');
const preload=read('desktop/preload.js'),main=read('desktop/main.js'),sdkMain=read('desktop/main-modules/sdk-export-runtime.js'),web=read('src/web-bridge.js');
assert(preload.includes("exportSdkBundle: () =>")&&preload.includes("ipcRenderer.invoke('sdk:exportBundle'"),'Electron preload must expose the SDK bundle export bridge.');
assert(main.includes('sdkExportRuntime.install(ipcMain)')&&sdkMain.includes("ipcMain.handle('sdk:exportBundle'")&&sdkMain.includes("nativeSaveRuntime.authorized(payload,'export')")&&sdkMain.includes("src','generated','dkds-sdk-export.zip"),'Electron main must install one bounded SDK export runtime that owns the save dialog, enforces explicit export intent and copies the generated SDK archive.');
