const generator=read('scripts/generate-sdk-authoring-reference.js');
assert(generator.includes("const exportOutput = path.join(root, 'src', 'generated', 'dkds-sdk-export.zip')")&&generator.includes("...walk('sdk')")&&generator.includes('AI_START_HERE.md')&&generator.includes('SDK_MANIFEST.json'),'SDK authoring generation must also build the complete AI-transferable SDK archive.');
const zipPath=path.join(root,'src/generated/dkds-sdk-export.zip');
assert(fs.existsSync(zipPath),'SDK export archive must be generated by sdk:authoring.');
const entries=storedZipEntries(fs.readFileSync(zipPath));
assert(entries.has('AI_START_HERE.md')&&entries.has('SDK_MANIFEST.json'),'SDK ZIP must contain AI handoff instructions and a machine-readable manifest.');
for(const rel of walk('sdk'))assert(entries.has(rel),`SDK ZIP is missing public SDK file: ${rel}`);
