(() => {
  'use strict';
  function mount(ctx,page,actions={}){
    const units=ctx.ui.unitTemplates,dom=ctx.ui.dom;
    const controls=new Map(),buttons=new Map(),disposables=[];
    let currentCurves=[],plotRevision=0;
    const field=(host,id,label,value,opts={})=>{
      const kind=opts.kind||'input';
      const item=units.field.create(host,{label,value,kind,variant:kind==='select'?'select':'input',inputType:opts.inputType||'number',options:opts.options||[],min:opts.min,max:opts.max,step:opts.step||'any',placeholder:opts.placeholder||'',onChange:()=>actions.onEdit?.(id)});
      controls.set(id,item.control);
      return item.control;
    };
    const action=(host,id,label,primary=false)=>{
      const item=units.action.create(host,{id,label,variant:primary?'primary':undefined,direct:true,onInvoke:()=>actions[id]?.()});
      buttons.set(id,item.button);return item.button;
    };
    const body=units.page.create(page,{variant:'tool'}).element;
    units.pageHeader.create(body,{variant:'page-owned',activity:'keithley-4200',title:'Keithley 4200A · 测量工作台',subtitle:'KXCI · 网络配置 / 测试设计 / 仿真实时曲线'});
    const workspaceHost=units.layout.create(body,{variant:'identity'});
    const workbench=units.workspace.create(workspaceHost,{variant:'standard',header:false,activity:'keithley-4200',primaryScroll:'safe'});
    const main=units.layout.create(null,{variant:'stack-comfortable'});
    units.note.create(main,{variant:'normal',text:'安全说明：此版本只允许真实设备 Connect / Identify / Disconnect；测量按钮仅启动本地仿真，不发送 SMU 输出命令。所有限流、电压数值仅为待验证的测试方案。'});
    const conn=units.panel.create(main,{variant:'headed',title:'连接与设备配置',sizing:'content'});
    const cgrid=units.layout.create(conn.body,{variant:'form-grid-2'});
    field(cgrid,'host','仪器 IP / 主机名','169.254.111.118',{inputType:'text'});
    field(cgrid,'port','TCP 端口',1225,{step:1});
    // Desktop Electron may relay through Android. Android itself and LAN web
    // browsers should only offer local Ethernet/Wi-Fi network bindings.
    const desktopHost=ctx.services?.get?.('tcp')?.supportsRelay===true;
    const modes=[{value:'auto',label:'自动（系统路由）'},{value:'wifi',label:'Wi-Fi 直连'},{value:'ethernet',label:'网线直连'},{value:'interface',label:'指定本机网卡'}];
    if(desktopHost)modes.push({value:'via-mobile',label:'通过安卓平板（LAN 网关）'});
    field(cgrid,'networkMode','连接方式','auto',{kind:'select',options:modes});
    field(cgrid,'interfaceName','网卡名称（指定接口时使用）','eth0',{inputType:'text'});
    if(desktopHost){
      units.note.create(conn.body,{variant:'meta',text:'通过安卓平板：电脑与平板连接同一可信 Wi-Fi，平板开启「局域网网页版」并启用配对 Key；平板可再通过网线或 Wi-Fi 访问仪器。当前远程操作仅支持 *IDN? 身份查询。'});
      field(cgrid,'mobileHost','平板 Wi-Fi IPv4 地址','192.168.1.100',{inputType:'text'});
      field(cgrid,'mobilePort','平板网页服务端口',45910,{step:1});
      field(cgrid,'mobilePairKey','平板当前 4 位配对 Key','',{inputType:'password'});
      field(cgrid,'mobileNetworkMode','平板到仪器的连接方式','ethernet',{kind:'select',options:[{value:'ethernet',label:'平板网线'},{value:'wifi',label:'平板 Wi-Fi'},{value:'auto',label:'平板自动'},{value:'interface',label:'平板指定接口'}]});
    }
    field(cgrid,'connectTimeoutMs','连接超时 (ms)',5000,{step:1});
    field(cgrid,'readTimeoutMs','响应超时 (ms)',5000,{step:1});
    field(cgrid,'expectedSerial','序列号校验（留空不校验）','1498377',{inputType:'text'});
    field(cgrid,'profileName','配置名称','我的 4200A',{inputType:'text'});
    field(cgrid,'profiles','已保存配置','',{kind:'select',options:[{value:'',label:'— 尚无保存配置 —'}]});
    const connActions=units.layout.create(conn.body,{variant:'action-grid-4'});
    action(connActions,'connect','连接 TCP');
    action(connActions,'identify','识别仪器',true);
    action(connActions,'disconnect','断开');
    action(connActions,'saveProfile','保存配置');
    action(connActions,'loadProfile','加载配置');
    const statePanel=units.panel.create(main,{variant:'headed',title:'设备状态',sizing:'content'});
    const stateNote=units.note.create(statePanel.body,{variant:'normal',text:'未连接'});
    const responseNote=units.note.create(statePanel.body,{variant:'meta',text:'—'});
    const design=units.panel.create(main,{variant:'headed',title:'测试方案编辑器 · 仅仿真',sizing:'content'});
    const dgrid=units.layout.create(design.body,{variant:'form-grid-2'});
    field(dgrid,'mode','测试类型','iv',{kind:'select',options:[{value:'iv',label:'I–V 曲线'},{value:'transfer',label:'转移特性'},{value:'output',label:'输出特性'},{value:'timed',label:'时间响应'}]});
    field(dgrid,'direction','扫描方向','roundtrip',{kind:'select',options:[{value:'forward',label:'正向'},{value:'reverse',label:'反向'},{value:'roundtrip',label:'正反往返'}]});
    field(dgrid,'loops','循环次数',3,{step:1});
    field(dgrid,'points','每单程点数',101,{step:1});
    field(dgrid,'startV','扫描起始值 (V)',-1);
    field(dgrid,'stopV','扫描终止值 (V)',1);
    field(dgrid,'complianceA','电流限值 (A)',0.0001);
    field(dgrid,'delayMs','采样间隔 / 延迟 (ms)',20);
    field(dgrid,'speed','速度预设','normal',{kind:'select',options:[{value:'fast',label:'快速'},{value:'normal',label:'标准'},{value:'quiet',label:'低噪声'}]});
    field(dgrid,'sourceSmU','扫描 / 源 SMU',1,{step:1});
    field(dgrid,'measureSmU','读数 SMU（可与扫描相同）',2,{step:1});
    field(dgrid,'gateSmU','Gate SMU（0 = 不使用）',3,{step:1});
    field(dgrid,'gateBiasV','栅极偏置 (V)',0);
    const designActions=units.layout.create(design.body,{variant:'action-grid-4'});
    action(designActions,'preview','验证并预览方案');
    action(designActions,'simulate','开始模拟采集',true);
    action(designActions,'stop','停止模拟采集');
    const previewNote=units.note.create(design.body,{variant:'meta',text:'请先验证方案。'});
    const originals=units.panel.create(main,{variant:'headed',title:'仪器原生数据与图片归档 · 尚未接通',sizing:'content'});
    units.note.create(originals.body,{variant:'normal',text:'目标：直接保存 4200A 仪器侧生成的测量数据文件及 Clarius / KXCI 原生图文件或原始屏幕截图。保存原文件字节，不做插值、拟合、重采样、重新绘图或图片重编码。'});
    units.note.create(originals.body,{variant:'meta',text:'当前仅能连接并读取 *IDN?。原生文件获取尚未实现；下方所有曲线与导出均为本地 SIMULATION 调试产物，不属于仪器原件。Clarius 与 KXCI 不可同时运行，原生图文件获取路径需按实际模式验证。'});
    const chart=units.panel.create(main,{variant:'headed',title:'本地仿真预览 · 不是仪器实时曲线',sizing:'content'});
    const progressNote=units.note.create(chart.body,{variant:'normal',text:'尚无仿真数据'});
    const plotHost=units.layout.create(chart.body,{variant:'identity',geometry:{width:'100%',minHeight:'300px'}});
    const plot=units.scientificPlot.create(plotHost,{variant:'curve',source:'keithley-4200:simulation',minHeight:300,xTitle:'Source voltage (V) / Time index',yTitle:'Current (A)',legend:{enabled:true,placement:'auto',interaction:'isolate',maxRows:2},getCurves:()=>currentCurves,getMarkers:()=>[]});
    const tableHost=units.layout.create(chart.body,{variant:'identity',geometry:{minHeight:'150px'}});
    const columns=[{key:'cycle',label:'Cycle'},{key:'point',label:'Point'},{key:'elapsed_s',label:'Time (s)'},{key:'set_v',label:'Set (V)'},{key:'read_v',label:'Read (V)'},{key:'read_a',label:'Current (A)'},{key:'status',label:'Status'}];
    const table=units.table.mount('keithley-4200-sim-data',tableHost,{variant:'standard',columns,rows:[]});
    const exportActions=units.layout.create(chart.body,{variant:'action-grid-4'});
    action(exportActions,'exportCsv','仿真 CSV').dataset.dkdsNativeSave='export';
    action(exportActions,'exportJson','仿真 JSON').dataset.dkdsNativeSave='export';
    action(exportActions,'exportSvg','软件生成 SVG').dataset.dkdsNativeSave='export';
    workbench.compose({primary:{id:'main',label:'4200A',presentationRole:'utility-primary',scroll:'safe',titlePolicy:'host-only',mainNode:main},primes:[],subs:[]});
    const get=id=>controls.get(id)?.value;
    const set=(id,value)=>{const node=controls.get(id);if(node)node.value=String(value??'');};
    const setOptions=(id,rows,value='')=>{const node=controls.get(id);if(!node)return;node.replaceChildren();for(const r of rows){const option=dom.create('option');option.value=String(r.value);option.textContent=String(r.label);node.appendChild(option);}node.value=String(value);};
    const renderStatus=(headline,detail)=>{stateNote.textContent=String(headline||'未连接');responseNote.textContent=String(detail||'—');};
    const renderPreview=text=>{previewNote.textContent=String(text||'');};
    const renderProgress=text=>{progressNote.textContent=String(text||'');};
    const renderData=(curves,rows)=>{currentCurves=curves||[];table.setData?.(columns,rows||[]);plot.requestRender?.('keithley-4200:sim:'+ ++plotRevision);};
    const setRunning=running=>{if(buttons.get('simulate'))buttons.get('simulate').disabled=!!running;if(buttons.get('stop'))buttons.get('stop').disabled=!running;};
    setRunning(false);
    return Object.freeze({get,set,setOptions,renderStatus,renderPreview,renderProgress,renderData,setRunning,dispose(){table.dispose?.();plot.dispose?.();workbench.dispose?.();}});
  }
  window.DKDSPluginModules.define('com.dkds.keithley-4200','unit-presentation',Object.freeze({mount}));
})();